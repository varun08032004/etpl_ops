const fs = require('fs');

const lines = [
  '/**',
  ' * Field Encryption Service - Versioned AES-256-GCM Keyring',
  ' *',
  ' * This is a VERSIONED AES-256-GCM KEYRING, not full envelope encryption.',
  ' * It does NOT generate per-field data-encryption keys wrapped by a master key.',
  ' * Instead, it uses a rotating set of master keys directly for AES-256-GCM.',
  ' *',
  ' * This is a deliberate design choice for simplicity and auditability.',
  ' * True envelope encryption (per-field DEK wrapped by KEK) would add complexity',
  ' * without proportional security benefit for our use case (field-level PII/credential encryption).',
  ' *',
  ' * Security properties:',
  ' * - AES-256-GCM authenticated encryption',
  ' * - Unique 12-byte nonce per encryption operation',
  ' * - Versioned ciphertext envelope with key ID, algorithm, version',
  ' * - AAD binding to (table, column, record_id) context',
  ' * - Key rotation via keyring with multiple active key IDs',
  ' * - Fail-closed on missing/malformed keys or unsupported versions',
  ' *',
  ' * Envelope format (base64):',
  ' *   v1:<keyId>:<base64(nonce)>:<base64(ciphertext+tag)>',
  ' *',
  ' * AAD format (not encrypted, used for GCM authentication):',
  ' *   table=<table>&column=<column>&record_id=<recordId>',
  ' */',
  '',
  "'use strict';",
  '',
  'const crypto = require("crypto");',
  '',
  'const ENVELOPE_VERSION = "v1";',
  'const SUPPORTED_VERSIONS = ["v1"];',
  'const NONCE_BYTES = 12; // 96 bits for GCM',
  'const TAG_BYTES = 16;   // 128 bits for GCM',
  'const KEY_BYTES = 32;   // 256 bits for AES-256',
  'const KEY_HEX_LENGTH = KEY_BYTES * 2; // 64 hex chars',
  '',
  '/**',
  ' * Custom error class for encryption failures',
  ' */',
  'class EncryptionError extends Error {',
  '  constructor(message, code) {',
  '    super(message);',
  '    this.name = "EncryptionError";',
  '    this.code = code || "ENCRYPTION_FAILED";',
  '  }',
  '}',
  '',
  '/**',
  ' * Field Encryption Service - Versioned AES-256-GCM Keyring',
  ' */',
  'class FieldEncryption {',
  '  constructor(options = {}) {',
  '    this.keyring = new Map(); // keyId -> { key: Buffer, metadata: Object }',
  '    this.activeKeyId = options.activeKeyId || null;',
  '    this.allowedVersions = options.allowedVersions || SUPPORTED_VERSIONS;',
  '    ',
  '    // Initialize from environment if provided',
  '    if (options.keys) {',
  '      for (const [keyId, keyHex] of Object.entries(options.keys)) {',
  '        this.addKey(keyId, keyHex, options.keyMetadata?.[keyId] || {});',
  '      }',
  '    }',
  '    ',
  '    // Set active key ID',
  '    if (this.activeKeyId && !this.keyring.has(this.activeKeyId)) {',
  '      throw new EncryptionError(`Active key ID "${this.activeKeyId}" not found in keyring`, \'INVALID_ACTIVE_KEY\');',
  '    }',
  '  }',
  '',
  '  /**',
  '   * Add a key to the keyring',
  '   * @param {string} keyId - Key identifier',
  '   * @param {string} keyHex - 64-char hex string (32 bytes)',
  '   * @param {Object} metadata - Optional metadata',
  '   */',
  '  addKey(keyId, keyHex, metadata = {}) {',
  '    if (!keyHex || typeof keyHex !== "string") {',
  '      throw new EncryptionError(`Key "${keyId}" must be a hex string`, "INVALID_KEY_FORMAT");',
  '    }',
  '    if (keyHex.length !== KEY_HEX_LENGTH) {',
  '      throw new EncryptionError(`Key "${keyId}" must be ${KEY_HEX_LENGTH} hex characters (${KEY_BYTES} bytes)`, "INVALID_KEY_LENGTH");',
  '    }',
  '    if (!/^[0-9a-fA-F]+$/.test(keyHex)) {',
  '      throw new EncryptionError(`Key "${keyId}" must be valid hex`, "INVALID_KEY_FORMAT");',
  '    }',
  '    ',
  '    const keyBuffer = Buffer.from(keyHex, "hex");',
  '    this.keyring.set(keyId, {',
  '      key: keyBuffer,',
  '      metadata: {',
  '        addedAt: new Date().toISOString(),',
  '        algorithm: "AES-256-GCM",',
  '        ...metadata',
  '      }',
  '    });',
  '    ',
  '    // Set as active if it is the first key',
  '    if (!this.activeKeyId) {',
  '      this.activeKeyId = keyId;',
  '    }',
  '  }',
  '',
  '  /**',
  '   * Set the active key ID',
  '   * @param {string} keyId - Key identifier',
  '   */',
  '  setActiveKey(keyId) {',
  '    if (!this.keyring.has(keyId)) {',
  '      throw new EncryptionError(`Key "${keyId}" not found in keyring`, "KEY_NOT_FOUND");',
  '    }',
  '    this.activeKeyId = keyId;',
  '  }',
  '',
  '  /**',
  '   * Get key by ID',
  '   * @param {string} keyId - Key identifier',
  '   * @returns {Buffer|null}',
  '   */',
  '  getKey(keyId) {',
  '    const entry = this.keyring.get(keyId);',
  '    return entry ? entry.key : null;',
  '  }',
  '',
  '  /**',
  '   * Get active key',
  '   * @returns {Buffer}',
  '   */',
  '  getActiveKey() {',
  '    if (!this.activeKeyId) {',
  '      throw new EncryptionError("No active key configured", "NO_ACTIVE_KEY");',
  '    }',
  '    return this.getActiveKeyBuffer();',
  '  }',
  '',
  '  getActiveKeyBuffer() {',
  '    const key = this.keyring.get(this.activeKeyId)?.key;',
  '    if (!key) {',
  '      throw new EncryptionError(`Active key "${this.activeKeyId}" not found`, \'ACTIVE_KEY_MISSING\');',
  '    }',
  '    return key;',
  '  }',
  '',
  '  /**',
  '   * Build AAD (Additional Authenticated Data) for GCM',
  '   * @param {string} table - Table name',
  '   * @param {string} column - Column name',
  '   * @param {string} recordId - Record identifier',
  '   * @returns {Buffer}',
  '   */',
  '  buildAAD(table, column, recordId) {',
  '    const aadString = `table=${table}&column=${column}&record_id=${recordId}`;',
  '    return Buffer.from(aadString, "utf8");',
  '  }',
  '',
  '  /**',
  '   * Parse envelope header',
  '   * @param {string} envelope - Base64 envelope string',
  '   * @returns {Object} Parsed envelope parts',
  '   */',
  '  parseEnvelope(envelope) {',
  '    if (!envelope || typeof envelope !== "string") {',
  '      throw new EncryptionError("Envelope must be a non-empty string", "INVALID_ENVELOPE");',
  '    }',
  '    ',
  '    const parts = envelope.split(":");',
  '    if (parts.length !== 4) {',
  '      throw new EncryptionError("Invalid envelope format: expected v1:keyId:nonce:ciphertext", "INVALID_ENVELOPE_FORMAT");',
  '    }',
  '    ',
  '    const [version, keyId, nonceB64, ciphertextB64] = parts;',
  '    ',
  '    if (!SUPPORTED_VERSIONS.includes(version)) {',
  '      throw new EncryptionError(`Unsupported envelope version: ${version}`, "UNSUPPORTED_VERSION");',
  '    }',
  '    ',
  '    let nonce, ciphertextWithTag;',
  '    try {',
  '      nonce = Buffer.from(nonceB64, "base64");',
  '      ciphertextWithTag = Buffer.from(ciphertextB64, "base64");',
  '    } catch (e) {',
  '      throw new EncryptionError("Invalid base64 in envelope", "INVALID_BASE64");',
  '    }',
  '    ',
  '    if (nonce.length !== NONCE_BYTES) {',
  '      throw new EncryptionError(`Invalid nonce length: expected ${NONCE_BYTES} bytes`, "INVALID_NONCE");',
  '    }',
  '    ',
  '    if (ciphertextWithTag.length < TAG_BYTES) {',
  '      throw new EncryptionError("Ciphertext too short", "INVALID_CIPHERTEXT");',
  '    }',
  '    ',
  '    const ciphertext = ciphertextWithTag.subarray(0, -TAG_BYTES);',
  '    const tag = ciphertextWithTag.subarray(-TAG_BYTES);',
  '    ',
  '    return { version, keyId, nonce, ciphertext, tag };',
  '  }',
  '',
  '  /**',
  '   * Encrypt a plaintext value',
  '   * @param {string} plaintext - Value to encrypt',
  '   * @param {Object} context - { table, column, recordId }',
  '   * @param {string} [keyId] - Optional specific key ID (uses active if not provided)',
  '   * @returns {string} Base64 envelope',
  '   */',
  '  encrypt(plaintext, context, keyId = null) {',
  '    if (plaintext === null || plaintext === undefined) {',
  '      throw new EncryptionError("Plaintext cannot be null or undefined", "INVALID_PLAINTEXT");',
  '    }',
  '    ',
  '    const plaintextStr = String(plaintext);',
  '    if (plaintextStr.length === 0) {',
  '      // Encrypt empty string as special case',
  '      return this.encryptEmpty(context, keyId);',
  '    }',
  '    ',
  '    const activeKeyId = keyId || this.activeKeyId;',
  '    if (!activeKeyId) {',
  '      throw new EncryptionError("No active key configured", "NO_ACTIVE_KEY");',
  '    }',
  '    ',
  '    const key = this.keyring.get(activeKeyId)?.key;',
  '    if (!key) {',
  '      throw new EncryptionError(`Key "${activeKeyId}" not found`, "KEY_NOT_FOUND");',
  '    }',
  '    ',
  '    const nonce = crypto.randomBytes(NONCE_BYTES);',
  '    const aad = this.buildAAD(context.table, context.column, context.recordId);',
  '    ',
  '    const cipher = crypto.createCipheriv("aes-256-gcm", key, nonce, {',
  '      authTagLength: TAG_BYTES',
  '    });',
  '    cipher.setAAD(aad);',
  '    ',
  '    const plaintextBuffer = Buffer.from(plaintextStr, "utf8");',
  '    const ciphertext = Buffer.concat([cipher.update(plaintextBuffer), cipher.final()]);',
  '    const tag = cipher.getAuthTag();',
  '    ',
  '    // Combine ciphertext + tag',
  '    const ciphertextWithTag = Buffer.concat([ciphertext, tag]);',
  '    ',
  '    // Build envelope: v1:keyId:base64(nonce):base64(ciphertext+tag)',
  '    const envelope = [',
  '      ENVELOPE_VERSION,',
  '      activeKeyId,',
  '      nonce.toString("base64"),',
  '      ciphertextWithTag.toString("base64")',
  '    ].join(":");',
  '    ',
  '    return envelope;',
  '  }',
  '',
  '  /**',
  '   * Encrypt empty string (special case)',
  '   */',
  '  encryptEmpty(context, keyId = null) {',
  '    // We still encrypt something to maintain format, but mark it specially',
  '    const emptyMarker = "\\u0000EMPTY\\u0000";',
  '    return this.encrypt(emptyMarker, context, keyId);',
  '  }',
  '',
  '  /**',
  '   * Check if envelope represents empty value',
  '   */',
  '  isEmptyEnvelope(envelope) {',
  '    try {',
  '      const decrypted = this.decrypt(envelope, { table: "", column: "", recordId: "" });',
  '      return decrypted === "\\u0000EMPTY\\u0000";',
  '    } catch {',
  '      return false;',
  '    }',
  '  }',
  '',
  '  /**',
  '   * Decrypt an envelope',
  '   * @param {string} envelope - Base64 envelope string',
  '   * @param {Object} context - { table, column, recordId } for AAD verification',
  '   * @returns {string} Decrypted plaintext',
  '   */',
  '  decrypt(envelope, context) {',
  '    if (!envelope || typeof envelope !== "string") {',
  '      throw new EncryptionError("Envelope must be a non-empty string", "INVALID_ENVELOPE");',
  '    }',
  '    ',
  '    const { keyId, nonce, ciphertext, tag } = this.parseEnvelope(envelope);',
  '    ',
  '    const key = this.keyring.get(keyId)?.key;',
  '    if (!key) {',
  '      throw new EncryptionError(`Key "${keyId}" not found in keyring`, "KEY_NOT_FOUND");',
  '    }',
  '    ',
  '    const aad = this.buildAAD(context.table, context.column, context.recordId);',
  '    ',
  '    const decipher = crypto.createDecipheriv("aes-256-gcm", key, nonce, {',
  '      authTagLength: TAG_BYTES',
  '    });',
  '    decipher.setAuthTag(tag);',
  '    decipher.setAAD(aad);',
  '    ',
  '    let plaintextBuffer;',
  '    try {',
  '      plaintextBuffer = Buffer.concat([decipher.update(ciphertext), decipher.final()]);',
  '    } catch (e) {',
  '      // Don\'t leak details about why decryption failed',
  '      throw new EncryptionError("Decryption failed: authentication tag mismatch or corrupted data", "DECRYPTION_FAILED");',
  '    }',
  '    ',
  '    const plaintext = plaintextBuffer.toString("utf8");',
  '    ',
  '    // Check for empty marker',
  '    if (plaintext === "\\u0000EMPTY\\u0000") {',
  '      return "";',
  '    }',
  '    ',
  '    return plaintext;',
  '  }',
  '',
  '  /**',
  '   * Get keyring status',
  '   * @returns {Object}',
  '   */',
  '  getStatus() {',
  '    const keys = [];',
  '    for (const [keyId, entry] of this.keyring.entries()) {',
  '      keys.push({',
  '        keyId,',
  '        active: keyId === this.activeKeyId,',
  '        algorithm: entry.metadata.algorithm,',
  '        addedAt: entry.metadata.addedAt,',
  '        rotatedAt: entry.metadata.rotatedAt',
  '      });',
  '    }',
  '    return {',
  '      activeKeyId: this.activeKeyId,',
  '      keyCount: this.keyring.size,',
  '      keys,',
  '      supportedVersions: this.allowedVersions',
  '    };',
  '  }',
  '',
  '  /**',
  '   * Rotate key: add new key, mark as active, keep old for decryption',
  '   * @param {string} newKeyId - New key identifier',
  '   * @param {string} newKeyHex - New key hex string',
  '   * @param {Object} metadata - Optional metadata',
  '   * @returns {Object} New key info',
  '   */',
  '  rotateKey(newKeyId, newKeyHex, metadata = {}) {',
  '    if (this.keyring.has(newKeyId)) {',
  '      throw new EncryptionError(`Key "${newKeyId}" already exists`, "KEY_EXISTS");',
  '    }',
  '    ',
  '    this.addKey(newKeyId, newKeyHex, { ...metadata, rotatedAt: new Date().toISOString() });',
  '    const oldActiveKeyId = this.activeKeyId;',
  '    this.setActiveKey(newKeyId);',
  '    ',
  '    return {',
  '      newKeyId,',
  '      previousActiveKeyId: oldActiveKeyId,',
  '      metadata: this.keyring.get(newKeyId).metadata',
  '    };',
  '  }',
  '',
  '  /**',
  '   * Re-encrypt envelope with active key (for key rotation)',
  '   * @param {string} envelope - Existing envelope',
  '   * @param {Object} context - AAD context',
  '   * @returns {string} New envelope encrypted with active key',
  '   */',
  '  reencrypt(envelope, context) {',
  '    const plaintext = this.decrypt(envelope, context);',
  '    return this.encrypt(plaintext, context);',
  '  }',
  '}',
  '',
  '/**',
  ' * Create FieldEncryption instance from environment',
  ' * Expected env vars:',
  ' * - FIELD_ENC_KEY_ACTIVE: active key ID',
  ' * - FIELD_ENC_KEY_<KEYID>: hex key for each key ID',
  ' */',
  'function createFromEnv() {',
  '  const activeKeyId = process.env.FIELD_ENC_KEY_ACTIVE;',
  '  const keys = {};',
  '  const keyMetadata = {};',
  '  ',
  '  for (const [envVar, value] of Object.entries(process.env)) {',
  '    const match = envVar.match(/^FIELD_ENC_KEY_(.+)$/);',
  '    if (match) {',
  '      const keyId = match[1];',
  '      if (keyId === "ACTIVE") continue;',
  '      if (value && value.length === 64 && /^[0-9a-fA-F]+$/.test(value)) {',
  '        keys[keyId] = value;',
  '      }',
  '    }',
  '  }',
  '  ',
  '  return new FieldEncryption({',
  '    activeKeyId,',
  '    keys,',
  '    keyMetadata',
  '  });',
  '}',
  '',
  'module.exports = {',
  '  FieldEncryption,',
  '  EncryptionError,',
  '  createFromEnv,',
  '  ENVELOPE_VERSION,',
  '  SUPPORTED_VERSIONS,',
  '  NONCE_BYTES,',
  '  TAG_BYTES,',
  '  KEY_BYTES,',
  '  KEY_HEX_LENGTH',
  '};',
];

